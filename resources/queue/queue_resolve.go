package queue

import (
	"context"

	"strings"

	"github.com/newstack-cloud/bluelink-transformer-celerity/shared"

	"github.com/newstack-cloud/bluelink/libs/blueprint/linktypes"
	"github.com/newstack-cloud/bluelink/libs/blueprint/schema"
	"github.com/newstack-cloud/bluelink/libs/plugin-framework/sdk/transformutils"
)

// TopicForwardEdge captures a resolved celerity/queue -> celerity/topic edge:
// the queue's messages are forwarded to the topic. How that forwarding is
// carried out is the deploy target's concern.
type TopicForwardEdge struct {
	// TopicName is the abstract topic resource name the queue forwards to.
	TopicName string
	// SelectorLabels are the topic labels the queue's link selector matched,
	// reconstructed from the edge's selector keys. Whatever a target emits to do
	// the forwarding carries these as its own link selector, so the target's own
	// link resolves them to the concrete topic.
	SelectorLabels map[string]string
}

// ResolvedQueue carries the abstract queue through to the emit phase. Beyond the
// queue's own metadata (labels + linkSelector are preserved as-is), it records any
// outbound celerity/topic forwarding edges so the emit can provision the
// intermediary forwarder, and whether the queue is also consumed (which competes
// with forwarding for the queue's messages).
type ResolvedQueue struct {
	Name          string
	Resource      *schema.Resource
	TopicForwards []*TopicForwardEdge
	// Consumed is true when a celerity/consumer links to this queue. Recorded
	// here because a target whose forwarding also consumes the queue has to
	// know: competing for one queue's messages is not the same as fanning them
	// out, so such a target rejects a queue that is both.
	Consumed bool
	// External is set when the resource points at a queue the target environment
	// already has and Celerity does not own, in which case no concrete resource
	// is emitted for it.
	External *shared.External
}

func (q *ResolvedQueue) ResourceName() string {
	return q.Name
}

func (q *ResolvedQueue) ResourceType() string {
	return "celerity/queue"
}

func resolveQueue(
	_ context.Context,
	_ *transformutils.Run,
	name string,
	resource *schema.Resource,
	linkGraph linktypes.DeclaredLinkGraph,
	_ *schema.Blueprint,
) (transformutils.ResolvedResource, error) {
	forwards, consumed := outboundEdges(name, linkGraph)
	external, _ := shared.ResolvedExternal("celerity/queue", name, resource)

	return &ResolvedQueue{
		Name:          name,
		Resource:      resource,
		TopicForwards: forwards,
		Consumed:      consumed,
		External:      external,
	}, nil
}

// outboundEdges collects the queue's outbound celerity/topic forwarding edges from
// the declared link graph (parsing each edge's selector keys into the topic labels
// the forwarder must carry) and reports whether the queue is also consumed (has an
// outbound celerity/consumer edge).
func outboundEdges(name string, linkGraph linktypes.DeclaredLinkGraph) ([]*TopicForwardEdge, bool) {
	if linkGraph == nil {
		return nil, false
	}
	var forwards []*TopicForwardEdge
	consumed := false
	for _, edge := range linkGraph.EdgesFrom(name) {
		if edge == nil {
			continue
		}
		switch edge.TargetType {
		case "celerity/topic":
			forwards = append(forwards, &TopicForwardEdge{
				TopicName:      edge.Target,
				SelectorLabels: labelsFromSelectorKeys(edge.SelectorKeys),
			})
		case "celerity/consumer":
			consumed = true
		}
	}
	return forwards, consumed
}

// labelsFromSelectorKeys parses selector keys of the form "label::<key>:<value>"
// (as generated by the blueprint selector grouping) into a label map.
func labelsFromSelectorKeys(keys []string) map[string]string {
	labels := map[string]string{}
	for _, key := range keys {
		trimmed := strings.TrimPrefix(key, "label::")
		if trimmed == key {
			continue
		}
		name, value, ok := strings.Cut(trimmed, ":")
		if !ok || name == "" {
			continue
		}
		labels[name] = value
	}
	return labels
}
